#!/usr/bin/env node
/**
 * Generate docs/rules.md from the rule definitions.
 *   node scripts/gen-rules-doc.mjs          write the file
 *   node scripts/gen-rules-doc.mjs --check  fail if it is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { loadScanner } from '../tests/helpers/scanner.mjs';

const OUT = new URL('../docs/rules.md', import.meta.url);
const { engine, config } = loadScanner();
const rules = engine.describeRules();

const SET_TITLES = {
  vendor: 'Vendor credentials',
  generic: 'Heuristics (keyword + entropy)',
  infrastructure: 'Infrastructure',
  debug: 'Debug artifacts',
};
const cell = (s) =>
  String(s || '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

const lines = [
  '# Detection rules',
  '',
  '<!-- Generated by scripts/gen-rules-doc.mjs — do not edit by hand. -->',
  '',
  `${rules.length} regex rules plus structural checks. The severity shown is the default;`,
  'rules can reclassify a hit after validating it (for example a JWT is decoded and a Supabase',
  '`anon` key becomes Info while `service_role` becomes Critical).',
  '',
];
for (const set of config.RULE_SETS) {
  const inSet = rules.filter((r) => r.set === set);
  lines.push(
    `## ${SET_TITLES[set]} (${inSet.length})`,
    '',
    '| ID | Title | Default severity | Confidence |',
    '|---|---|---|---|',
  );
  for (const r of inSet) lines.push(`| \`${r.id}\` | ${cell(r.title)} | ${r.severity} | ${r.confidence} |`);
  lines.push('');
}
lines.push(
  '## Structural checks',
  '',
  '| ID | What it checks |',
  '|---|---|',
  '| `prefilled-password-input` | `<input type="password">` shipped with a `value` attribute |',
  '| `storage-sensitive-key` | Session/credential-named Web Storage keys whose values matched no rule |',
  '| `cookie-not-httponly` | Session-like cookies visible to `document.cookie` (so missing HttpOnly) |',
  '| `source-map-exposed` | A referenced `.map` file is publicly reachable (its original sources are then scanned) |',
  '',
);

const content = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== content) {
    console.error('✗ docs/rules.md is out of date — run: npm run docs:rules');
    process.exit(1);
  }
  console.log(`✓ docs/rules.md is current (${rules.length} rules)`);
} else {
  writeFileSync(OUT, content);
  console.log(`wrote docs/rules.md (${rules.length} rules)`);
}
